-- Phase 3a: generic document workflow, sub-ledger posting, tax codes, GL account mappings,
-- suppliers, supplier invoices (AP), disbursement vouchers, bank accounts, check register, budgets.

-- ---------------------------------------------------------------- generic workflow & sub-ledger posting
CREATE TABLE document_workflow_steps (
    id                   UUID PRIMARY KEY,
    document_type        VARCHAR(30)   NOT NULL,
    step_order           SMALLINT      NOT NULL CHECK (step_order > 0),
    step_code            VARCHAR(20)   NOT NULL,
    required_permission  VARCHAR(64)   NOT NULL REFERENCES permissions (code),
    min_amount           NUMERIC(19,2) CHECK (min_amount IS NULL OR min_amount >= 0),
    CONSTRAINT uq_document_workflow_step UNIQUE (document_type, step_order)
);

ALTER TABLE approval_decisions DROP CONSTRAINT approval_decisions_action_check;
ALTER TABLE approval_decisions ADD CONSTRAINT approval_decisions_action_check
    CHECK (action IN ('SUBMIT', 'APPROVE', 'RETURN', 'REJECT', 'CANCEL', 'POST', 'INSTRUCT', 'CONFIRM', 'VOID'));

ALTER TABLE approval_workflows DROP CONSTRAINT approval_workflows_voucher_type_check;
ALTER TABLE approval_workflows ADD CONSTRAINT approval_workflows_voucher_type_check
    CHECK (voucher_type IN ('STANDARD', 'ADJUSTING', 'REVERSAL', 'OPENING', 'RECURRING', 'CLOSING', 'SUBLEDGER'));
INSERT INTO approval_workflows (voucher_type, description, requires_attachment)
VALUES ('SUBLEDGER', 'Entry generated by a sub-ledger document approved in its own module', FALSE);

-- Each sub-ledger event (source types prefixed SL_) can reach the general ledger at most once.
CREATE UNIQUE INDEX uq_je_subledger_source ON journal_entries (source_type, source_reference)
    WHERE source_type LIKE 'SL\_%';

-- Configurable control accounts used by automatic postings (e.g. AP_TRADE_PAYABLE, INPUT_VAT).
CREATE TABLE gl_account_mappings (
    mapping_key  VARCHAR(40)  PRIMARY KEY CHECK (mapping_key ~ '^[A-Z][A-Z0-9_]{2,39}$'),
    account_id   UUID         NOT NULL REFERENCES chart_of_accounts (id),
    description  VARCHAR(300) NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    updated_by   VARCHAR(64)  NOT NULL
);

-- ---------------------------------------------------------------- tax codes
CREATE TABLE tax_codes (
    id           UUID PRIMARY KEY,
    code         VARCHAR(20)   NOT NULL UNIQUE,
    description  VARCHAR(300)  NOT NULL,
    tax_type     VARCHAR(12)   NOT NULL CHECK (tax_type IN ('EWT', 'VAT_INPUT', 'VAT_OUTPUT', 'FINAL_VAT')),
    rate         NUMERIC(7,4)  NOT NULL CHECK (rate >= 0 AND rate < 1),
    account_id   UUID          NOT NULL REFERENCES chart_of_accounts (id),
    status       VARCHAR(10)   NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    placeholder  BOOLEAN       NOT NULL DEFAULT FALSE,
    version      BIGINT        NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ   NOT NULL,
    created_by   VARCHAR(64)   NOT NULL
);

-- ---------------------------------------------------------------- suppliers
CREATE TABLE suppliers (
    id                     UUID PRIMARY KEY,
    code                   VARCHAR(40)   NOT NULL UNIQUE,
    name                   VARCHAR(200)  NOT NULL,
    tin                    VARCHAR(20)   CHECK (tin IS NULL OR tin ~ '^[0-9]{3}-?[0-9]{3}-?[0-9]{3}(-?[0-9]{3,5})?$'),
    address                VARCHAR(500),
    vat_registered         BOOLEAN       NOT NULL,
    default_ewt_code_id    UUID          REFERENCES tax_codes (id),
    subsidiary_account_id  UUID          NOT NULL UNIQUE REFERENCES subsidiary_ledger_accounts (id),
    status                 VARCHAR(10)   NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    version                BIGINT        NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ   NOT NULL,
    created_by             VARCHAR(64)   NOT NULL,
    updated_at             TIMESTAMPTZ   NOT NULL,
    updated_by             VARCHAR(64)   NOT NULL
);
CREATE UNIQUE INDEX uq_suppliers_tin ON suppliers (replace(tin, '-', '')) WHERE tin IS NOT NULL;

-- ---------------------------------------------------------------- supplier invoices (accounts payable)
CREATE TABLE supplier_invoices (
    id                   UUID PRIMARY KEY,
    supplier_id          UUID          NOT NULL REFERENCES suppliers (id),
    invoice_number       VARCHAR(60)   NOT NULL,
    invoice_date         DATE          NOT NULL,
    due_date             DATE          NOT NULL,
    accounting_date      DATE          NOT NULL,
    period_id            UUID          NOT NULL REFERENCES accounting_periods (id),
    description          VARCHAR(1000) NOT NULL,
    status               VARCHAR(12)   NOT NULL CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'POSTED', 'RETURNED', 'REJECTED', 'CANCELLED')),
    current_step_order   SMALLINT,
    vat_code_id          UUID          REFERENCES tax_codes (id),
    net_amount           NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (net_amount >= 0),
    vat_amount           NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (vat_amount >= 0),
    ewt_amount           NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (ewt_amount >= 0),
    payable_amount       NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (payable_amount >= 0),
    paid_amount          NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    prepared_by_id       UUID          NOT NULL REFERENCES users (id),
    prepared_by          VARCHAR(64)   NOT NULL,
    posted_entry_id      UUID          REFERENCES journal_entries (id),
    version              BIGINT        NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ   NOT NULL,
    updated_at           TIMESTAMPTZ   NOT NULL,
    updated_by           VARCHAR(64)   NOT NULL,
    CONSTRAINT ck_inv_due CHECK (due_date >= invoice_date),
    CONSTRAINT ck_inv_paid CHECK (paid_amount <= payable_amount)
);
-- Duplicate-invoice control: one live invoice per supplier and invoice number.
CREATE UNIQUE INDEX uq_supplier_invoice_live ON supplier_invoices (supplier_id, lower(invoice_number))
    WHERE status NOT IN ('REJECTED', 'CANCELLED');
CREATE INDEX ix_supplier_invoices_status ON supplier_invoices (status, due_date);

CREATE TABLE supplier_invoice_lines (
    id              UUID PRIMARY KEY,
    invoice_id      UUID          NOT NULL REFERENCES supplier_invoices (id) ON DELETE CASCADE,
    line_no         SMALLINT      NOT NULL,
    account_id      UUID          NOT NULL REFERENCES chart_of_accounts (id),
    cost_center_id  UUID          REFERENCES cost_centers (id),
    description     VARCHAR(500),
    net_amount      NUMERIC(19,2) NOT NULL CHECK (net_amount > 0),
    ewt_code_id     UUID          REFERENCES tax_codes (id),
    ewt_amount      NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (ewt_amount >= 0),
    CONSTRAINT uq_sil_line UNIQUE (invoice_id, line_no)
);

-- ---------------------------------------------------------------- treasury base
CREATE TABLE bank_accounts (
    id                     UUID PRIMARY KEY,
    code                   VARCHAR(30)   NOT NULL UNIQUE,
    bank_name              VARCHAR(200)  NOT NULL,
    account_name           VARCHAR(200)  NOT NULL,
    -- Only the last four digits are stored; full numbers stay with the bank and treasury records.
    account_number_last4   CHAR(4)       NOT NULL CHECK (account_number_last4 ~ '^[0-9]{4}$'),
    gl_account_id          UUID          NOT NULL REFERENCES chart_of_accounts (id),
    status                 VARCHAR(10)   NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    version                BIGINT        NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ   NOT NULL,
    created_by             VARCHAR(64)   NOT NULL
);

-- ---------------------------------------------------------------- disbursement vouchers
CREATE TABLE disbursement_vouchers (
    id                   UUID PRIMARY KEY,
    dv_number            VARCHAR(30)   UNIQUE,
    supplier_id          UUID          NOT NULL REFERENCES suppliers (id),
    particulars          VARCHAR(1000) NOT NULL,
    status               VARCHAR(20)   NOT NULL CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'PAYMENT_INSTRUCTED',
                                                                  'PAID', 'POSTED', 'RETURNED', 'REJECTED', 'CANCELLED')),
    current_step_order   SMALLINT,
    amount               NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    payment_mode         VARCHAR(10)   CHECK (payment_mode IN ('CHECK', 'ADA')),
    bank_account_id      UUID          REFERENCES bank_accounts (id),
    payment_reference    VARCHAR(60),
    payment_date         DATE,
    instructed_by        VARCHAR(64),
    instructed_at        TIMESTAMPTZ,
    confirmed_by         VARCHAR(64),
    confirmed_at         TIMESTAMPTZ,
    prepared_by_id       UUID          NOT NULL REFERENCES users (id),
    prepared_by          VARCHAR(64)   NOT NULL,
    posted_entry_id      UUID          REFERENCES journal_entries (id),
    version              BIGINT        NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ   NOT NULL,
    updated_at           TIMESTAMPTZ   NOT NULL,
    updated_by           VARCHAR(64)   NOT NULL
);
CREATE INDEX ix_dv_status ON disbursement_vouchers (status);

CREATE TABLE disbursement_voucher_lines (
    id          UUID PRIMARY KEY,
    dv_id       UUID          NOT NULL REFERENCES disbursement_vouchers (id) ON DELETE CASCADE,
    invoice_id  UUID          NOT NULL REFERENCES supplier_invoices (id),
    amount      NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    CONSTRAINT uq_dvl_invoice UNIQUE (dv_id, invoice_id)
);
CREATE INDEX ix_dvl_invoice ON disbursement_voucher_lines (invoice_id);

CREATE TABLE check_register (
    id               UUID PRIMARY KEY,
    bank_account_id  UUID          NOT NULL REFERENCES bank_accounts (id),
    check_number     VARCHAR(20)   NOT NULL,
    dv_id            UUID          NOT NULL REFERENCES disbursement_vouchers (id),
    payee            VARCHAR(200)  NOT NULL,
    amount           NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    issue_date       DATE          NOT NULL,
    status           VARCHAR(10)   NOT NULL CHECK (status IN ('ISSUED', 'RELEASED', 'VOIDED', 'CLEARED')),
    void_reason      VARCHAR(500),
    created_at       TIMESTAMPTZ   NOT NULL,
    created_by       VARCHAR(64)   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    updated_by       VARCHAR(64)   NOT NULL,
    CONSTRAINT uq_check_number UNIQUE (bank_account_id, check_number)
);
-- At most one live (issued or released) check per DV.
CREATE UNIQUE INDEX uq_check_live_dv ON check_register (dv_id) WHERE status IN ('ISSUED', 'RELEASED');

-- ---------------------------------------------------------------- budgeting
CREATE TABLE budgets (
    id                  UUID PRIMARY KEY,
    fiscal_year_id      UUID          NOT NULL UNIQUE REFERENCES fiscal_years (id),
    name                VARCHAR(200)  NOT NULL,
    status              VARCHAR(12)   NOT NULL CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'RETURNED')),
    current_step_order  SMALLINT,
    prepared_by_id      UUID          NOT NULL REFERENCES users (id),
    prepared_by         VARCHAR(64)   NOT NULL,
    approved_at         TIMESTAMPTZ,
    approved_by         VARCHAR(64),
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    updated_by          VARCHAR(64)   NOT NULL
);

CREATE TABLE budget_allocations (
    id              UUID PRIMARY KEY,
    budget_id       UUID          NOT NULL REFERENCES budgets (id) ON DELETE CASCADE,
    account_id      UUID          NOT NULL REFERENCES chart_of_accounts (id),
    cost_center_id  UUID          REFERENCES cost_centers (id),
    amount          NUMERIC(19,2) NOT NULL CHECK (amount >= 0),
    version         BIGINT        NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uq_budget_allocation ON budget_allocations
    (budget_id, account_id, coalesce(cost_center_id, '00000000-0000-0000-0000-000000000000'::uuid));

CREATE TABLE budget_reservations (
    id             UUID PRIMARY KEY,
    allocation_id  UUID          NOT NULL REFERENCES budget_allocations (id),
    source_type    VARCHAR(30)   NOT NULL,
    source_id      UUID          NOT NULL,
    amount         NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    status         VARCHAR(10)   NOT NULL CHECK (status IN ('ACTIVE', 'CONSUMED', 'RELEASED')),
    created_at     TIMESTAMPTZ   NOT NULL,
    updated_at     TIMESTAMPTZ   NOT NULL
);
CREATE INDEX ix_budget_reservations_allocation ON budget_reservations (allocation_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_budget_reservations_source ON budget_reservations (source_type, source_id);

CREATE TABLE budget_adjustments (
    id                  UUID PRIMARY KEY,
    budget_id           UUID          NOT NULL REFERENCES budgets (id),
    from_allocation_id  UUID          REFERENCES budget_allocations (id),
    to_allocation_id    UUID          NOT NULL REFERENCES budget_allocations (id),
    amount              NUMERIC(19,2) NOT NULL CHECK (amount > 0),
    reason              VARCHAR(1000) NOT NULL,
    status              VARCHAR(10)   NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    requested_by_id     UUID          NOT NULL REFERENCES users (id),
    requested_by        VARCHAR(64)   NOT NULL,
    requested_at        TIMESTAMPTZ   NOT NULL,
    decided_by_id       UUID          REFERENCES users (id),
    decided_by          VARCHAR(64),
    decided_at          TIMESTAMPTZ,
    CONSTRAINT ck_adjustment_two_people CHECK (decided_by_id IS NULL OR decided_by_id <> requested_by_id),
    CONSTRAINT ck_adjustment_distinct CHECK (from_allocation_id IS NULL OR from_allocation_id <> to_allocation_id)
);
