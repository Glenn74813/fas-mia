#!/usr/bin/env node
// Traceability between the UAT scripts (docs/uat/*.md) and the requirements matrix (docs/02-requirements-traceability.md).
//
//   node scripts/uat/coverage.mjs                         check, then write docs/uat/coverage.md and docs/uat/tracker.csv
//   node scripts/uat/coverage.mjs --results <tracker.csv> also report the pass rate of a filled-in tracker (MS §18: ≥ 95 %,
//                                                          100 % of required cases, no critical defects)
// Exits non-zero when a script cites an unknown requirement, a done or in-progress requirement has no script (and is
// not listed in docs/uat/README.md as verified by automated tests only), or a script ID is duplicated.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const UAT = join(ROOT, 'docs', 'uat');
const problems = [];

// Requirements: functional rows of the matrix with their status.
const requirements = new Map();
for (const line of readFileSync(join(ROOT, 'docs', '02-requirements-traceability.md'), 'utf8').split('\n')) {
  const cells = line.split('|').map((c) => c.trim());
  if (/^FR-/.test(cells[1] ?? '')) requirements.set(cells[1], { requirement: cells[3], status: cells[6] });
}
const needsScript = (status) => /^(Done|In progress)/i.test(status);

// Requirements verified by automated tests only (README table).
const readme = readFileSync(join(UAT, 'README.md'), 'utf8');
const automatedOnly = new Set([...readme.split('## Requirements verified by automated tests only')[1]?.matchAll(/^\| (FR-[A-Z0-9.-]+) \|/gm) ?? []]
  .map((m) => m[1]));

// Scripts.
const scripts = [];
for (const file of readdirSync(UAT).filter((f) => /^\d\d-.*\.md$/.test(f)).sort()) {
  const text = readFileSync(join(UAT, file), 'utf8');
  for (const block of text.split(/^### /m).slice(1)) {
    const head = /^(UAT-[A-Z]+-\d{3}) (.+)$/m.exec(block);
    if (!head) {
      problems.push(`${file}: a script heading lacks an ID: "${block.split('\n')[0]}"`);
      continue;
    }
    const rtm = (/^- RTM: (.+)$/m.exec(block)?.[1] ?? '').split(',').map((s) => s.trim()).filter(Boolean);
    const roles = /^- Roles: (.+)$/m.exec(block)?.[1] ?? '';
    const steps = (block.match(/^\| \d+ \|/gm) ?? []).length;
    if (!rtm.length) problems.push(`${head[1]}: no RTM line`);
    if (!steps) problems.push(`${head[1]}: no steps`);
    for (const r of rtm) if (!requirements.has(r)) problems.push(`${head[1]}: cites ${r}, which is not in the matrix`);
    scripts.push({ id: head[1], title: head[2], file, rtm, roles, steps });
  }
}
const ids = new Map();
for (const s of scripts) ids.set(s.id, (ids.get(s.id) ?? 0) + 1);
for (const [id, n] of ids) if (n > 1) problems.push(`${id} is used ${n} times`);
for (const r of automatedOnly) if (!requirements.has(r)) problems.push(`README lists ${r}, which is not in the matrix`);

// Coverage.
const byReq = new Map([...requirements.keys()].map((r) => [r, []]));
for (const s of scripts) for (const r of s.rtm) byReq.get(r)?.push(s.id);
const rows = [...requirements].map(([id, r]) => {
  const covered = byReq.get(id);
  const coverage = covered.length ? covered.join(', ') : automatedOnly.has(id) ? 'automated tests only' : needsScript(r.status) ? 'MISSING' : 'not built yet';
  if (coverage === 'MISSING') problems.push(`${id} (${r.status.slice(0, 40)}) has no UAT script`);
  return { id, requirement: r.requirement, status: r.status.split(/[:;(]/)[0].trim(), coverage };
});

const md = ['# UAT coverage (generated)', '', `Generated by \`scripts/uat/coverage.mjs\` from ${scripts.length} scripts and the requirements matrix. Do not edit by hand.`, '',
  '| Requirement | Description | Status | UAT scripts |', '|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.requirement} | ${r.status} | ${r.coverage} |`), ''].join('\n');
writeFileSync(join(UAT, 'coverage.md'), md);
const csv = (v) => `"${String(v).replace(/"/g, '""')}"`;
writeFileSync(join(UAT, 'tracker.csv'), ['id,title,file,rtm,roles,steps,result,tester,date,defect_id,severity,notes',
  ...scripts.map((s) => [s.id, s.title, s.file, s.rtm.join('; '), s.roles, s.steps, '', '', '', '', '', ''].map(csv).join(','))].join('\n') + '\n');

console.log(`${scripts.length} scripts, ${scripts.reduce((t, s) => t + s.steps, 0)} steps; ${rows.filter((r) => /^UAT/.test(r.coverage)).length} requirements `
  + `covered by scripts, ${rows.filter((r) => r.coverage === 'automated tests only').length} by automated tests only, `
  + `${rows.filter((r) => r.coverage === 'not built yet').length} not built yet.`);

// Results of a filled-in tracker.
const resultsArg = process.argv.indexOf('--results');
if (resultsArg > 0) {
  const path = process.argv[resultsArg + 1];
  if (!path || !existsSync(path)) throw new Error(`No tracker file at ${path}`);
  const parse = (line) => [...line.matchAll(/("([^"]|"")*"|[^,]*)(,|$)/g)].map((m) => m[1].replace(/^"|"$/g, '').replace(/""/g, '"')).slice(0, -1);
  const [header, ...lines] = readFileSync(path, 'utf8').trim().split('\n');
  const cols = parse(header);
  const recs = lines.map((l) => Object.fromEntries(parse(l).map((v, i) => [cols[i], v])));
  const result = (r) => r.result.trim().toUpperCase();
  const passed = recs.filter((r) => result(r) === 'PASS').length;
  const failed = recs.filter((r) => result(r) === 'FAIL');
  const blocked = recs.filter((r) => result(r) === 'BLOCKED').length;
  const notRun = recs.length - passed - failed.length - blocked;
  const critical = recs.filter((r) => /critical/i.test(r.severity ?? '') && result(r) !== 'PASS');
  const rate = recs.length ? passed / recs.length : 0;
  console.log(`Results: ${passed} passed, ${failed.length} failed, ${blocked} blocked, ${notRun} not run of ${recs.length}; `
    + `pass rate ${(rate * 100).toFixed(1)} % (§18 needs ≥ 95 % and every required case passed).`);
  for (const f of failed) console.log(`  FAIL ${f.id} ${f.title} — defect ${f.defect_id || '?'} (${f.severity || 'no severity'})`);
  if (critical.length) console.log(`  ${critical.length} unresolved critical defect(s): acceptance is not possible.`);
  const acceptable = rate >= 0.95 && notRun === 0 && blocked === 0 && failed.length === 0 && critical.length === 0;
  console.log(acceptable ? 'UAT meets the §18 test conditions.' : 'UAT does not yet meet the §18 test conditions.');
}

if (problems.length) {
  console.error(`\n${problems.length} traceability problem(s):\n` + problems.map((p) => `  - ${p}`).join('\n'));
  process.exit(1);
}
