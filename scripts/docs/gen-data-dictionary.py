#!/usr/bin/env python3
"""Regenerates the schema sections of docs/04-data-model.md (migration index, ERDs, data dictionary).

Reads the live schema of a migrated database and the comments in the Flyway migrations; table purposes come
from table-purposes.json next to this script. Everything before the marker line in 04-data-model.md is kept.

Usage: PGPASSWORD=... python3 scripts/docs/gen-data-dictionary.py [--host localhost --port 55432 --db cas --user cas]
"""
import argparse, json, os, re, subprocess
from collections import OrderedDict, defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
MIG = os.path.join(ROOT, 'backend', 'src', 'main', 'resources', 'db', 'migration')
DOC = os.path.join(ROOT, 'docs', '04-data-model.md')
MARKER = '<!-- generated by scripts/docs/gen-data-dictionary.py: do not edit below this line -->'

ap = argparse.ArgumentParser()
ap.add_argument('--host', default='localhost'); ap.add_argument('--port', default='55432')
ap.add_argument('--db', default='cas'); ap.add_argument('--user', default='cas')
args = ap.parse_args()


def q(sql):
    out = subprocess.run(['psql', '-h', args.host, '-p', args.port, '-U', args.user, '-d', args.db, '-At', '-F', '\x1f', '-c', sql],
                         capture_output=True, text=True, check=True).stdout
    return [line.split('\x1f') for line in out.splitlines() if line]


def vnum(f):
    return int(re.match(r'V(\d+)__', f).group(1))


files = sorted([f for f in os.listdir(MIG) if f.endswith('.sql')], key=vnum)
PURPOSE = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'table-purposes.json')))

# ---------------------------------------------------------------- migration comments
created_in, table_note, col_note, added_in = {}, {}, defaultdict(dict), defaultdict(dict)
for f in files:
    text = open(os.path.join(MIG, f)).read()
    lines = text.split('\n')
    for i, line in enumerate(lines):
        m = re.match(r'\s*CREATE\s+(?:UNLOGGED\s+)?TABLE\s+(?:IF NOT EXISTS\s+)?([a-z_0-9]+)\s*\(', line, re.I)
        if not m:
            continue
        t = m.group(1)
        created_in.setdefault(t, f)
        j, block = i - 1, []
        if j >= 0 and not lines[j].strip():
            j -= 1
        while j >= 0 and lines[j].strip().startswith('--') and not lines[j].strip().startswith('-- ---'):
            block.insert(0, lines[j].strip()[2:].strip())
            j -= 1
        note = ' '.join(b for b in block if b and not set(b) <= set('-= '))
        if note and j >= 0:  # j < 0 means the block is the file header, already in the migration index
            table_note.setdefault(t, note)
        pending, k = [], i + 1
        while k < len(lines) and not re.match(r'\s*\);', lines[k]):
            s = lines[k].strip()
            if s.startswith('--'):
                pending.append(s[2:].strip())
            else:
                cm = re.match(r'([a-z_0-9]+)\s+[A-Za-z]', s)
                if cm and cm.group(1).upper() not in ('CONSTRAINT', 'PRIMARY', 'UNIQUE', 'CHECK', 'FOREIGN', 'EXCLUDE'):
                    inline = s.split('--', 1)[1].strip() if '--' in s else ''
                    note = ' '.join(pending + ([inline] if inline else []))
                    if note:
                        col_note[t].setdefault(cm.group(1), note)
                pending = []
            k += 1
    for m in re.finditer(r'ALTER\s+TABLE\s+([a-z_0-9]+)([^;]*);', text, re.I):
        for c in re.findall(r'ADD\s+COLUMN\s+(?:IF NOT EXISTS\s+)?([a-z_0-9]+)', m.group(2), re.I):
            added_in[m.group(1)].setdefault(c, f)

# ---------------------------------------------------------------- catalogue
tables = [r[0] for r in q("""SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> 'flyway_schema_history' ORDER BY 1""")]
unlogged = {r[0] for r in q("SELECT relname FROM pg_class WHERE relpersistence = 'u' AND relkind = 'r'")}
cols = defaultdict(list)
for t, c, typ, nn, dflt in q("""SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull::text,
        coalesce(pg_get_expr(d.adbin, d.adrelid), '')
    FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE n.nspname = 'public' AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped ORDER BY c.relname, a.attnum"""):
    cols[t].append((c, typ, nn == 'true', dflt))
cons, fks = defaultdict(list), []
for t, name, typ, defn in q("""SELECT c.relname, k.conname, k.contype, pg_get_constraintdef(k.oid) FROM pg_constraint k
    JOIN pg_class c ON c.oid = k.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' ORDER BY 1, 2"""):
    cons[t].append((name, typ, defn))
    m = re.match(r'FOREIGN KEY \(([^)]+)\) REFERENCES ([a-z_0-9]+)\(([^)]+)\)', defn) if typ == 'f' else None
    if m:
        fks.append((t, m.group(1).strip(), m.group(2)))
idx = defaultdict(list)
for t, name, defn in q("SELECT tablename, indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' ORDER BY 1, 2"):
    idx[t].append((name, defn))
trg = defaultdict(list)
for t, name, defn in q("""SELECT c.relname, tg.tgname, pg_get_triggerdef(tg.oid) FROM pg_trigger tg JOIN pg_class c ON c.oid = tg.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND NOT tg.tgisinternal ORDER BY 1, 2"""):
    trg[t].append((name, defn))

# ---------------------------------------------------------------- domains
DOMAINS = OrderedDict([
    ('Identity, access and sessions', r'^(users|roles|permissions|role_permissions|user_roles|sod_conflict_rules|user_sessions|refresh_tokens|mfa_methods|mfa_recovery_codes|mfa_email_codes|webauthn_|password_reset_tokens|access_review|role_grant|approval_limit|api_rate)'),
    ('Organisation', r'^(organizations|offices|departments|user_office)'),
    ('General ledger and journals', r'^(currencies|fiscal_years|accounting_periods|period_status|chart_of_accounts|cost_centers|subsidiary_ledger|numbering|approval_workflow|journal_|approval_decisions|ledger_balances|recurring_journal|gl_clearing|gl_account_mappings|tax_codes|close_task)'),
    ('Documents, workflow and idempotency', r'^(supporting_documents|document_contents|document_workflow|idempotency_keys)'),
    ('Budgeting', r'^budget'),
    ('Payables', r'^(suppliers|supplier_bank|supplier_invoice|disbursement|check_|payment_)'),
    ('Receivables and portal', r'^(customers|customer_|billing|receipt|portal_)'),
    ('Treasury', r'^(bank_|deposit)'),
    ('Fixed assets', r'^(asset_|fixed_asset|auc_|depreciation)'),
    ('Inventory', r'^(inventory|warehouse|gr_ir)'),
    ('Reporting', r'^report_'),
    ('Integrations and notifications', r'^(integration|notification|alert_throttle|api_clients|webhook_)'),
    ('Tickets', r'^(ticket|sla_|business_holidays)'),
    ('Audit', r'^(audit_events|security_events|anomaly_findings|data_exports|legal_holds)'),
    ('Migration and parallel run', r'^(migration|parallel_run|supplier_advances)'),
])
dom_of = {}
for t in tables:
    for d, pat in DOMAINS.items():
        if re.search(pat, t):
            dom_of.setdefault(t, d)
    dom_of.setdefault(t, 'Other')
by_dom = OrderedDict((d, []) for d in list(DOMAINS) + ['Other'])
for t in tables:
    by_dom[dom_of[t]].append(t)

GENERIC = {
    'id': 'Primary key (UUID generated by the application)', 'version': 'Optimistic-lock version, incremented on every update',
    'created_at': 'When the row was created', 'created_by': 'Username that created the row', 'updated_at': 'When the row last changed',
    'updated_by': 'Username that last changed the row', 'status': 'Lifecycle status; legal values in the rules below',
    'placeholder': 'TRUE for [PLACEHOLDER] seed data that MIAA must replace or confirm', 'description': 'Free-text description',
    'name': 'Display name', 'code': 'Business code', 'remarks': 'Free-text remarks', 'sort_order': 'Display order',
    'currency_code': 'ISO 4217 currency (PHP only today)', 'posted_entry_id': 'Journal entry created when the document was posted',
    'prepared_by': 'Username of the preparer', 'current_step_order': 'Current workflow step (NULL when not awaiting approval)',
    'content_encryption': "Encryption scheme of the stored bytes ('NONE' or the AES-256-GCM scheme of V35)",
    'cancel_reason': 'Reason given when cancelled', 'row_hash': 'SHA-256 of this row chained to the previous one',
    'prev_hash': 'Row hash of the previous event in the chain',
}


def meaning_of(c, fk_target):
    if c in GENERIC:
        return GENERIC[c]
    if fk_target:
        return f'References `{fk_target}`'
    if c.endswith('_at'):
        return 'When ' + c[:-3].replace('_', ' ')
    if c.endswith('_date'):
        return c[:-5].replace('_', ' ').capitalize() + ' date'
    return ''


def readable(defn):
    defn = re.sub(r"\(\(\(?([a-z_]+)\)?(?:::text)? = ANY \(\(?ARRAY\[([^\]]+)\]\)?(?:::text\[\])?\)\)\)",
                  lambda m: m.group(1) + ' IN (' + ', '.join(re.findall(r"'([^']*)'", m.group(2))) + ')', defn)
    return re.sub(r"::(character varying|text|numeric|integer|bigint|bpchar)(\[\])?", '', defn)


def esc(s):
    return s.replace('|', '\\|').replace('\n', ' ')


def short_type(typ):
    return (typ.replace('character varying', 'varchar').replace('timestamp with time zone', 'timestamptz')
            .replace('character', 'char').replace('boolean', 'bool'))


out = [MARKER, '', '## 2. Migration index', '', '| Version | File | Purpose (from the migration header) |', '|---|---|---|']
for f in files:
    head = []
    for line in open(os.path.join(MIG, f)).read().split('\n'):
        if line.startswith('--'):
            head.append(line[2:].strip())
        elif line.strip():
            break
    sentences = re.split(r'(?<=\.)\s', ' '.join(h for h in head if h))
    out.append(f'| V{vnum(f)} | `{f}` | {esc(" ".join(sentences[:2]))} |')
out += ['', '## 3. Entity-relationship diagrams by domain', '',
        "Generated from the foreign keys of the live schema. Each diagram shows the domain's tables with their primary-key "
        'and foreign-key columns; references to tables of other domains are listed under the diagram.', '']
fkcols = defaultdict(set)
for t, c, rt in fks:
    for x in c.split(','):
        fkcols[t].add(x.strip())
for n, (d, ts) in enumerate([(d, ts) for d, ts in by_dom.items() if ts], 1):
    tset = set(ts)
    out += [f'### 3.{n} {d}', '', '```mermaid', 'erDiagram']
    for t in ts:
        pk = set()
        for name, typ, defn in cons[t]:
            if typ == 'p':
                pk |= {c.strip() for c in re.match(r'PRIMARY KEY \(([^)]+)\)', defn).group(1).split(',')}
        out.append(f'    {t} {{')
        for c, typ, nn, dflt in cols[t]:
            if c in pk or c in fkcols[t]:
                tag = 'PK' if c in pk else ''
                if c in fkcols[t]:
                    tag = (tag + ',FK') if tag else 'FK'
                ty = re.sub(r'[^a-z0-9_]', '_', short_type(typ).split('(')[0].replace(' ', '_'))
                out.append(f'        {ty} {c} {tag}')
        out.append('    }')
    external, seen = set(), set()
    for t, c, rt in fks:
        if t in tset and rt in tset and (t, rt, c) not in seen:
            seen.add((t, rt, c))
            nullable = any(col == c.split(',')[0].strip() and not nn for col, typ, nn, dflt in cols[t])
            out.append(f'    {rt} {"|o--o{" if nullable else "||--o{"} {t} : "{c}"')
        elif t in tset:
            external.add(f'`{t}.{c}` → `{rt}`')
    out += ['```', '']
    if external:
        out += ['References to other domains: ' + '; '.join(sorted(external)) + '.', '']
out += ['## 4. Data dictionary', '',
        'One section per table, in domain order. *Created in* names the migration that created the table; columns added '
        'later name their migration. Column meanings come from the migration comments, then from naming conventions '
        '(keys, foreign keys, audit columns); a blank meaning means the column name is the whole story or the table '
        'notes explain it. Rules (CHECK, UNIQUE and partial indexes, triggers) are copied from the database catalogue.', '']
for n, (d, ts) in enumerate([(d, ts) for d, ts in by_dom.items() if ts], 1):
    out += [f'### 4.{n} {d}', '']
    for t in ts:
        made = created_in.get(t, '?')
        note = table_note.get(t, '')
        purpose = PURPOSE.get(t, '')
        out += [f'#### `{t}`' + (' (UNLOGGED)' if t in unlogged else ''), '',
                f'Created in `{made}`. ' + esc(purpose) + (f' *Migration note:* {esc(note)}' if note and note not in purpose else ''), '',
                '| Column | Type | Null | Default | Meaning |', '|---|---|---|---|---|']
        fkt = {fc: rt for ft, fc, rt in fks if ft == t and ',' not in fc}
        for c, typ, nn, dflt in cols[t]:
            m = col_note[t].get(c, '') or meaning_of(c, fkt.get(c))
            if c in added_in.get(t, {}) and added_in[t][c] != made:
                m = (m + ' ' if m else '') + f'(added in V{vnum(added_in[t][c])})'
            out.append(f'| {c} | {esc(short_type(typ))} | {"N" if nn else "Y"} | {esc(dflt)} | {esc(m)} |')
        rules = [f'`{name}`: {esc(readable(defn))}' for name, typ, defn in cons[t] if typ in ('c', 'u', 'x')]
        connames = {name for name, _, _ in cons[t]}
        for name, defn in idx[t]:
            if name in connames:
                continue
            if ' WHERE ' in defn or 'UNIQUE' in defn:
                body = defn.split(' USING ', 1)[1] if ' USING ' in defn else defn
                rules.append(f'`{name}`: {"UNIQUE " if "UNIQUE" in defn else ""}INDEX {esc(readable(body))}')
        for name, defn in trg[t]:
            rules.append(f'trigger `{name}`: {esc(re.sub(r"^CREATE (CONSTRAINT )?TRIGGER [a-z_0-9]+ ", "", defn).replace(" ON public." + t, ""))}')
        if rules:
            out += ['', 'Rules: ' + '; '.join(rules) + '.']
        out.append('')

doc = open(DOC).read()
head = doc.split(MARKER)[0].rstrip() + '\n\n' if MARKER in doc else doc.rstrip() + '\n\n'
open(DOC, 'w').write(head + '\n'.join(out) + '\n')
missing = [t for t in tables if t not in PURPOSE]
print(f'{len(tables)} tables in {sum(1 for v in by_dom.values() if v)} domains; other: {by_dom["Other"]}; without purpose: {missing}')
